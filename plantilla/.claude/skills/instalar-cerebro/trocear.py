#!/usr/bin/env python3
"""Saca los chats de Claude del dueño a un archivo de texto por chat, para la instalación del cerebro.

Uso (desde la carpeta del cerebro):
  python3 .claude/skills/instalar-cerebro/trocear.py --listar-code
      Lista las carpetas con chats de la pestaña Code de este ordenador.
  python3 .claude/skills/instalar-cerebro/trocear.py [--code <carpeta> ...] [--code-todas] [--desde AAAA-MM-DD] [--tope N]
      Lee la exportación de claude.ai que haya en instalacion/ (el .zip o conversations.json)
      y los chats de Code que se le indiquen, y deja en instalacion/chats/ un .md por chat,
      ordenados por fecha. Se salta los chats de menos de 3 mensajes y los ya hechos
      (los que salen en instalacion/progreso.md).
      --desde: solo los chats con algún mensaje desde ese día (por defecto, los últimos 30 días).
      --tope: máximo de caracteres en total (por defecto 1.500.000); si no cabe todo, entran los chats
      más recientes y los demás se listan en instalacion/fuera-por-tope.md.
Antes de escribir, limpia: quita el texto de las skills que la app mete en el turno del dueño, marca como
«Sistema» lo que no escribió él, numera los turnos y pone a cada uno su fecha real.
No necesita nada instalado: solo Python 3.
"""
import sys, json, re, zipfile, unicodedata
from pathlib import Path

CEREBRO = Path.cwd()
INST = CEREBRO / "instalacion"
CHATS = INST / "chats"
PROYECTOS = Path.home() / ".claude" / "projects"
MIN_MENSAJES = 3
MAX_CARACTERES = 90_000  # un chat más largo se corta en partes, por turnos enteros
TOPE = 1_500_000         # caracteres en total que se dan a leer en una instalación

SKILL = ("Base directory for this skill:",)
SISTEMA = ("Codebase and user instructions are shown below", "<task-notification>", "<system-reminder>",
           "[SYSTEM NOTIFICATION", "<bash-input>", "<bash-stdout>", "<local-command-stdout>", "<command-name>",
           "Caveat: The messages below were generated by the user while running local commands",
           "Stop hook feedback:", "[Image:", "[Request interrupted", "<scheduled-task", "[Usage limit reached",
           "This session is being continued from a previous conversation", "Another Claude session sent a message",
           "<agent-message", "<side-sessions-event>", "<cross-session-message")


def dia(ts):
    """Marca de tiempo del registro (UTC) → día local del ordenador."""
    from datetime import datetime
    try:
        return datetime.fromisoformat(ts.replace("Z", "+00:00")).astimezone().strftime("%Y-%m-%d")
    except Exception:
        return (ts or "")[:10]


def etiqueta(quien, t):
    """(quién, texto) ya limpio: lo que no escribió el dueño no se le atribuye."""
    s = t.strip()
    if quien != "Dueño":
        return quien, s
    if s.startswith(SKILL):
        m = re.match(r"Base directory for this skill: \S*/([\w.:-]+)\s", s)
        a = s.rfind("\nARGUMENTS:")
        arg = s[a + 11:].strip() if a >= 0 else ""
        aviso = f"[Se cargó la skill «{m.group(1) if m else '?'}»; su texto no se copia aquí.]"
        return ("Dueño", aviso + "\nLo que escribió al llamarla: " + arg) if arg else ("Sistema", aviso)
    if s.startswith(SISTEMA):
        return "Sistema", s if len(s) <= 2000 else s[:2000] + "\n[… recortado]"
    return "Dueño", s


def slug(t, n=50):
    t = unicodedata.normalize("NFD", t.lower())
    t = "".join(c for c in t if unicodedata.category(c) != "Mn")
    t = re.sub(r"[^a-z0-9]+", "-", t).strip("-")
    return (t[:n].rstrip("-") or "chat")


def hechos():
    p = INST / "progreso.md"
    if not p.exists():
        return set()
    nombres = re.findall(r"^- `?([^\s`]+?)(?:\.md)?`?\s*$", p.read_text(), re.M)
    return {n + ".md" for n in nombres}


def texto_bloques(c):
    if isinstance(c, str):
        return c
    out = []
    for b in c or []:
        if isinstance(b, dict) and b.get("type") == "text" and b.get("text"):
            out.append(b["text"])
    return "\n".join(out)


# ---------- claude.ai (exportación) ----------
def leer_export():
    datos = None
    for z in sorted(INST.glob("*.zip")):
        with zipfile.ZipFile(z) as f:
            for n in f.namelist():
                if n.endswith("conversations.json"):
                    datos = json.loads(f.read(n))
    for j in sorted(INST.rglob("conversations.json")):
        if "chats" not in j.parts:
            datos = json.loads(j.read_text())
    if datos is None:
        return []
    chats = []
    for conv in datos if isinstance(datos, list) else datos.get("conversations", []):
        msgs = []
        for m in conv.get("chat_messages", []):
            quien = "Dueño" if m.get("sender") == "human" else "Claude"
            t = m.get("text") or texto_bloques(m.get("content"))
            adj = []
            for a in (m.get("attachments") or []):
                nombre = a.get("file_name") or "adjunto"
                cont = a.get("extracted_content") or ""
                adj.append(f"[Adjunto: {nombre}]\n{cont}".rstrip())
            for f in (m.get("files") or []):
                if isinstance(f, dict) and f.get("file_name"):
                    adj.append(f"[Archivo: {f['file_name']} (sin texto en la exportación)]")
            cuerpo = "\n\n".join(x for x in [t.strip()] + adj if x)
            if cuerpo:
                msgs.append((quien, m.get("created_at", ""), cuerpo))
        fecha = (conv.get("created_at") or (msgs[0][1] if msgs else ""))[:10]
        titulo = conv.get("name") or (msgs[0][2][:60] if msgs else "chat")
        chats.append({"origen": "claude.ai", "id": (conv.get("uuid") or "")[:8], "fecha": fecha,
                      "titulo": titulo, "mensajes": msgs})
    return chats


# ---------- pestaña Code (transcripciones locales) ----------
def carpetas_code():
    yo = str(CEREBRO).replace("/", "-")
    out = []
    if PROYECTOS.is_dir():
        for d in sorted(PROYECTOS.iterdir()):
            if d.is_dir() and d.name != yo:
                n = len(list(d.glob("*.jsonl")))
                if n:
                    out.append((d, n))
    return out


def limpio(t):
    t = re.sub(r"<system-reminder>.*?</system-reminder>", "", t, flags=re.S)
    t = re.sub(r"<(command-[a-z-]+|local-command-[a-z-]+)>.*?</\1>", "", t, flags=re.S)
    return t.strip()


def leer_code(carpetas):
    chats = []
    for d in carpetas:
        for f in sorted(d.glob("*.jsonl")):
            msgs, fecha, titulo = [], "", ""
            for l in f.read_text(errors="replace").splitlines():
                try:
                    o = json.loads(l)
                except Exception:
                    continue
                if o.get("isSidechain") or o.get("type") not in ("user", "assistant"):
                    continue
                c = (o.get("message") or {}).get("content")
                if o["type"] == "user" and isinstance(c, list) and all(
                        isinstance(b, dict) and b.get("type") == "tool_result" for b in c):
                    continue
                t = limpio(texto_bloques(c))
                if not t:
                    continue
                fecha = fecha or (o.get("timestamp") or "")[:10]
                quien = "Dueño" if o["type"] == "user" else "Claude"
                if quien == "Dueño" and not titulo:
                    titulo = t[:60]
                msgs.append((quien, o.get("timestamp", ""), t))
            chats.append({"origen": f"Code · {d.name[-40:]}", "id": f.stem[:8], "fecha": fecha,
                          "titulo": titulo or "chat", "mensajes": msgs})
    return chats


def escribir(chats, desde, tope):
    CHATS.mkdir(parents=True, exist_ok=True)
    ya = hechos()
    nuevos = cortos = viejos = 0
    fuera = []
    chats = [c for c in chats if c["fecha"]]
    for c in chats:
        c["ultimo"] = max((dia(ts) for _, ts, _ in c["mensajes"] if ts), default=c["fecha"])
    chats.sort(key=lambda c: (c["ultimo"], c["id"]), reverse=True)   # los más recientes entran primero
    gastado = 0
    for c in chats:
        if len(c["mensajes"]) < MIN_MENSAJES:
            cortos += 1
            continue
        if c["ultimo"] < desde:
            viejos += 1
            continue
        nd = nc = 0
        turnos = []
        for q, ts, txt in c["mensajes"]:
            q, txt = etiqueta(q, txt)
            if not txt:
                continue
            d = dia(ts) if ts else ""
            if q == "Dueño":
                nd += 1; cab = f"## Dueño [{nd}]" + (f" · {d}" if d else "")
            elif q == "Claude":
                nc += 1; cab = f"## Claude [{nc}]" + (f" · {d}" if d else "")
            else:
                cab = "## Sistema"
            turnos.append(f"{cab}\n\n{txt}")
        partes, actual = [], ""
        for tu in turnos:
            if actual and len(actual) + len(tu) > MAX_CARACTERES:
                partes.append(actual); actual = ""
            actual += ("\n\n" if actual else "") + tu[:MAX_CARACTERES]
        if actual:
            partes.append(actual)
        total = sum(len(x) for x in partes)
        base = f"{c['fecha']}-{slug(c['titulo'])}-{c['id']}"
        if gastado + total > tope:
            fuera.append(f"- {base} ({total // 1000} mil caracteres, último mensaje el {c['ultimo']})")
            continue
        gastado += total
        for k, p in enumerate(partes, 1):
            nombre = base + (f"-parte{k}" if len(partes) > 1 else "") + ".md"
            if nombre in ya or (CHATS / nombre).exists():
                continue
            cab = f"# {' '.join(c['titulo'].split())}\nFecha: {c['fecha']} · Origen: {c['origen']} · Mensajes: {len(c['mensajes'])}"
            if len(partes) > 1:
                cab += f" · Parte {k} de {len(partes)}"
            (CHATS / nombre).write_text(cab + "\n\n" + p + "\n")
            nuevos += 1
    if fuera:
        (INST / "fuera-por-tope.md").write_text("Chats que no se han leído por el tope de la instalación (los más antiguos):\n" + "\n".join(fuera) + "\n")
    pend = sorted(x.name for x in CHATS.glob("*.md") if x.name not in ya)
    print(f"Chats por leer: {len(pend)} ({gastado // 1000} mil caracteres; nuevos ahora: {nuevos}; ya hechos antes: {len(ya)}; "
          f"cortos: {cortos}; anteriores al {desde}: {viejos}; fuera por el tope: {len(fuera)})")
    for n in pend:
        print("  " + n)


if __name__ == "__main__":
    a = sys.argv[1:]
    if "--listar-code" in a:
        cs = carpetas_code()
        if not cs:
            print("No hay chats de la pestaña Code en este ordenador.")
        for d, n in cs:
            print(f"{n:>4} chats · {d}")
        sys.exit(0)
    INST.mkdir(exist_ok=True)
    elegidas = []
    if "--code-todas" in a:
        elegidas = [d for d, _ in carpetas_code()]
    for i, x in enumerate(a):
        if x == "--code" and i + 1 < len(a):
            elegidas.append(Path(a[i + 1]).expanduser())
    from datetime import date, timedelta
    desde, tope = (date.today() - timedelta(days=30)).isoformat(), TOPE
    for i, x in enumerate(a):
        if x == "--desde" and i + 1 < len(a):
            desde = a[i + 1]
        if x == "--tope" and i + 1 < len(a):
            tope = int(a[i + 1])
    escribir(leer_export() + leer_code(elegidas), desde, tope)
